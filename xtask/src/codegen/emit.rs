    #[test]
    fn templates_and_raw_strings() {
        let parts: Vec<String> = template("room-history/{shard}/{room}/{tick}.json")
            .into_iter()
            .map(|part| match part {
                Part::Literal(text) => format!("L:{text}"),
                Part::Param(name) => format!("P:{name}"),
            })
            .collect();
        assert_eq!(
            parts,
            [
                "L:room-history/",
                "P:shard",
                "L:/",
                "P:room",
                "L:/",
                "P:tick",
                "L:.json"
            ]
        );
        assert_eq!(raw_string("{}"), "r\"{}\"");
        assert_eq!(raw_string(r#"{"a":1}"#), "r#\"{\"a\":1}\"#");
        assert_eq!(raw_string("\"#"), "r##\"\"#\"##");
    }
